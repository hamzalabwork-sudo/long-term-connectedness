"""Write paper/suppnum.tex: the numbers of the supplementary tables, read from
supplementary.aux, so that main.tex can cite them (\\Sref{tab:...}) without the xr package
or a particular build order. Run after compiling supplementary.tex.

Usage:  python make_suppnum.py ../paper/supplementary.aux ../paper/suppnum.tex
"""
import re
import sys

aux, out = sys.argv[1], sys.argv[2]
labels = re.findall(r"\\newlabel\{(tab:[^}]+)\}\{\{([^}]*)\}", open(aux, encoding="utf-8").read())
with open(out, "w", encoding="utf-8") as f:
    f.write("% generated by code/make_suppnum.py from supplementary.aux; do not edit\n")
    for lab, num in labels:
        f.write(f"\\expandafter\\def\\csname sref@{lab}\\endcsname{{{num}}}\n")
print(f"wrote {len(labels)} labels:", ", ".join(f"{l}={n}" for l, n in labels))
